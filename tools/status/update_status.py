#!/usr/bin/env python3
"""Write status.md from the checked in parity measurement.

    update_status.py [--output status.md]

The numbers live in tools/parity/parity.json so the report is deterministic: the workflow
only commits status.md when the measurement itself changed. Re-measuring is a separate step,
because it needs the vanilla server and its region files:

    update_status.py --measure <vanilla-dump> <terila-dump> [--input input]
                     [--seed 12345] [--chunk 0 0]

That rewrites tools/parity/parity.json and then the report.
"""

import argparse
import datetime
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
PARITY_DIR = os.path.join(ROOT, "tools", "parity")
PARITY_JSON = os.path.join(PARITY_DIR, "parity.json")
sys.path.insert(0, PARITY_DIR)

import compare  # noqa: E402  (the tool lives next to this one)


def render(parity):
    blocks = parity["blocks"]
    biomes = parity.get("biomes", {})
    lines = [
        "# Project status",
        "",
        "Generated by the Update Status workflow from `tools/parity/parity.json`; edit the "
        "measurement, not this file.",
        "",
        "## World generation parity",
        "",
        "A chunk generated by Terila is compared block by block with the same chunk from a "
        "vanilla %s server (seed %d, chunk %d, %d)."
        % (parity["minecraft_version"], parity["seed"], parity["chunk"][0], parity["chunk"][1]),
        "",
        "| Measurement | Result |",
        "| --- | --- |",
        "| Blocks matching vanilla | %d / %d (%.2f%%)"
        % (blocks["matched"], blocks["compared"], blocks["percent"]),
    ]
    if biomes:
        lines.append("| Biomes matching vanilla | %d / %d (%.2f%%)"
                     % (biomes["matched"], biomes["compared"], biomes["percent"]))
    lines += [
        "",
        "### Blocks that differ, by height",
        "",
        "| Height | Mismatched | Total | Share |",
        "| --- | --- | --- | --- |",
    ]
    for entry in parity["bands"]:
        lines.append("| %s | %d | %d | %.2f%% |"
                     % (entry["band"], entry["wrong"], entry["total"], entry["percent"]))

    if parity["pairs"]:
        lines += [
            "",
            "### Most common remaining differences",
            "",
            "| Vanilla | Terila | Blocks |",
            "| --- | --- | --- |",
        ]
        for entry in parity["pairs"]:
            lines.append("| %s | %s | %d |"
                         % (entry["vanilla"], entry["terila"], entry["count"]))

    lines += ["", "_Measured %s._" % parity["measured_at"], ""]
    return "\n".join(lines)


def measure(args):
    result = compare.summarize(args.input, args.vanilla_dump, args.terila_dump)
    result.update({
        "measured_at": datetime.date.today().isoformat(),
        "minecraft_version": args.minecraft_version,
        "seed": args.seed,
        "chunk": list(args.chunk),
    })
    with open(PARITY_JSON, "w", encoding="utf-8", newline="\n") as file:
        json.dump(result, file, indent=2)
        file.write("\n")
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", default=os.path.join(ROOT, "status.md"))
    parser.add_argument("--measure", nargs=2, metavar=("VANILLA_DUMP", "TERILA_DUMP"))
    parser.add_argument("--input", default=os.path.join(ROOT, "input"))
    parser.add_argument("--seed", type=int, default=12345)
    parser.add_argument("--chunk", type=int, nargs=2, default=[0, 0])
    parser.add_argument("--minecraft-version", default="26.3")
    args = parser.parse_args()
    args.vanilla_dump = args.measure[0] if args.measure else None
    args.terila_dump = args.measure[1] if args.measure else None

    if args.measure:
        parity = measure(args)
    else:
        with open(PARITY_JSON, encoding="utf-8") as file:
            parity = json.load(file)

    with open(args.output, "w", encoding="utf-8", newline="\n") as file:
        file.write(render(parity))
    print("wrote %s" % os.path.relpath(args.output, ROOT))


if __name__ == "__main__":
    main()
