// Turns the manifest CMake writes into the C++ an embedded-input build compiles.
//
//   terila_embed_input <manifest> <output directory>
//
// One translation unit per chunk of at most manifest's chunk_bytes, plus a table that ties the
// chunks back to the file they came from. Chunking keeps a multi-megabyte data file from
// landing in a single translation unit, where the initialiser alone would dwarf the rest of
// the build.

#include <cstdint>
#include <filesystem>
#include <fstream>
#include <iostream>
#include <sstream>
#include <string>
#include <vector>

namespace {

    struct Chunk {
        int index = 0;
        long long offset = 0;
        long long length = 0;
        std::string path;
    };

    struct Entry {
        int index = 0;
        long long size = 0;
        int first_chunk = 0;
        int chunk_count = 0;
        std::string path;
    };

    struct Manifest {
        std::string input_dir;
        long long chunk_bytes = 0;
        std::vector<Entry> entries;
        std::vector<Chunk> chunks;
    };

    // Every line starts with a keyword; a path is always the last field and may contain spaces,
    // so the fixed fields come first and the rest of the line is read as-is.

    bool parse(const std::filesystem::path& file, Manifest& out) {
        std::ifstream in(file);
        if (!in) {
            std::cerr << "embed_input: cannot open manifest " << file << '\n';
            return false;
        }

        std::string line;
        while (std::getline(in, line)) {
            // CMake writes the manifest on the host, so a CRLF file leaves a stray '\r' on
            // every line; it is not part of any path or number here.
            while (!line.empty() && (line.back() == '\r' || line.back() == '\n')) {
                line.pop_back();
            }

            std::istringstream row(line);
            std::string kind;
            if (!(row >> kind)) {
                continue;
            }

            if (kind == "input_dir") {
                std::getline(row, out.input_dir);
                if (!out.input_dir.empty() && out.input_dir.front() == ' ') {
                    out.input_dir.erase(out.input_dir.begin());
                }
                continue;
            }

            if (kind == "chunk_bytes") {
                row >> out.chunk_bytes;
                continue;
            }

            Chunk chunk;
            if (kind == "chunk") {
                row >> chunk.index >> chunk.offset >> chunk.length;
                std::getline(row, chunk.path);
                if (!chunk.path.empty() && chunk.path.front() == ' ') {
                    chunk.path.erase(chunk.path.begin());
                }
                out.chunks.push_back(std::move(chunk));
                continue;
            }

            Entry entry;
            if (kind == "entry") {
                row >> entry.index >> entry.size >> entry.first_chunk >> entry.chunk_count;
                std::getline(row, entry.path);
                if (!entry.path.empty() && entry.path.front() == ' ') {
                    entry.path.erase(entry.path.begin());
                }
                out.entries.push_back(std::move(entry));
            }
        }

        if (out.input_dir.empty() || out.chunk_bytes <= 0 || out.chunks.empty() ||
            out.entries.empty()) {
            std::cerr << "embed_input: manifest " << file << " says nothing to embed\n";
            return false;
        }
        return true;
    }

    bool write(const std::filesystem::path& path, const std::string& text) {
        std::ofstream out(path, std::ios::binary);
        if (!out) {
            std::cerr << "embed_input: cannot write " << path << '\n';
            return false;
        }
        out << text;
        return out.good();
    }

    const char* kHeader =
        "#pragma once\n"
        "// Generated by tools/embed_input.cpp; do not edit.\n"
        "\n"
        "#include <cstddef>\n"
        "#include <cstdint>\n"
        "#include <string_view>\n"
        "\n"
        "namespace terila::embedded {\n"
        "\n"
        "    struct Chunk {\n"
        "        const std::uint8_t* data = nullptr;\n"
        "        std::size_t size = 0;\n"
        "    };\n"
        "\n"
        "    struct Entry {\n"
        "        std::string_view path;\n"
        "        const Chunk* chunks = nullptr;\n"
        "        std::size_t chunk_count = 0;\n"
        "    };\n"
        "\n";

    std::string chunk_source(int index, const std::filesystem::path& input,
        const Chunk& chunk) {
        std::ifstream file(input / chunk.path, std::ios::binary);
        if (!file) {
            std::cerr << "embed_input: cannot open " << (input / chunk.path) << '\n';
            return {};
        }
        file.seekg(chunk.offset);
        std::vector<char> bytes(static_cast<std::size_t>(chunk.length));
        file.read(bytes.data(), chunk.length);
        if (!file) {
            std::cerr << "embed_input: short read on " << chunk.path << " at " << chunk.offset << '\n';
            return {};
        }

        std::string text;
        text.reserve(static_cast<std::size_t>(chunk.length) * 6 + 256);
        text += "// Generated by tools/embed_input.cpp; do not edit.\n"
            "#include \"embedded_input.hpp\"\n"
            "\n"
            "namespace terila::embedded {\n"
            "\n"
            "    const std::uint8_t chunk_";
        text += std::to_string(index);
        text += "[] = {\n";

        constexpr int kBperLine = 16;
        for (std::size_t i = 0; i < bytes.size(); ++i) {
            if (i % kBperLine == 0) {
                text += "        ";
            }
            static const char* digits = "0123456789abcdef";
            const auto byte = static_cast<unsigned char>(bytes[i]);
            text += "0x";
            text += digits[byte >> 4];
            text += digits[byte & 0x0F];
            text += ',';
            if (i + 1 == bytes.size() || (i + 1) % kBperLine == 0) {
                text += '\n';
            }
        }

        text += "    };\n"
            "\n"
            "} // namespace terila::embedded\n";
        return text;
    }

    std::string table_source(const Manifest& manifest) {
        std::string text =
            "// Generated by tools/embed_input.cpp; do not edit.\n"
            "#include \"embedded_input.hpp\"\n"
            "\n"
            "namespace terila::embedded {\n"
            "\n"
            "    namespace {\n";

        for (const auto& entry : manifest.entries) {
            text += "\n        const Chunk chunks_";
            text += std::to_string(entry.index);
            text += "[] = {\n";
            for (int i = 0; i < entry.chunk_count; ++i) {
                const auto chunk_index = entry.first_chunk + i;
                const auto& chunk = manifest.chunks[static_cast<std::size_t>(chunk_index)];
                text += "            { chunk_";
                text += std::to_string(chunk_index);
                text += ", ";
                text += std::to_string(chunk.length);
                text += " },\n";
            }
            text += "        };\n";
        }

        text += "\n    } // namespace\n\n"
            "    const Entry entries[] = {\n";
        for (const auto& entry : manifest.entries) {
            text += "        { \"";
            text += entry.path;
            text += "\", chunks_";
            text += std::to_string(entry.index);
            text += ", ";
            text += std::to_string(entry.chunk_count);
            text += " },\n";
        }
        text += "    };\n\n"
            "    const std::size_t entry_count = sizeof(entries) / sizeof(entries[0]);\n"
            "\n"
            "} // namespace terila::embedded\n";
        return text;
    }

} // namespace

int main(int argc, char** argv) {
    if (argc != 3) {
        std::cerr << "usage: terila_embed_input <manifest> <output directory>\n";
        return 2;
    }

    const std::filesystem::path manifest_path = argv[1];
    const std::filesystem::path output = argv[2];

    Manifest manifest;
    if (!parse(manifest_path, manifest)) {
        return 1;
    }

    // The paths in the manifest are relative to the data directory, whose absolute location is
    // part of the manifest because the generator itself lives in the build tree.
    const std::filesystem::path input = manifest.input_dir;

    std::error_code ec;
    std::filesystem::create_directories(output, ec);
    if (ec) {
        std::cerr << "embed_input: cannot create " << output << ": " << ec.message() << '\n';
        return 1;
    }

    std::string header = kHeader;
    for (const auto& chunk : manifest.chunks) {
        header += "    extern const std::uint8_t chunk_";
        header += std::to_string(chunk.index);
        header += "[];\n";
    }
    header +=
        "\n"
        "    extern const Entry entries[];\n"
        "    extern const std::size_t entry_count;\n"
        "\n"
        "} // namespace terila::embedded\n";

    if (!write(output / "embedded_input.hpp", header)) {
        return 1;
    }

    for (const auto& chunk : manifest.chunks) {
        const auto text = chunk_source(chunk.index, input, chunk);
        if (text.empty()) {
            return 1;
        }
        if (!write(output / ("embedded_" + std::to_string(chunk.index) + ".cpp"), text)) {
            return 1;
        }
    }

    if (!write(output / "embedded_input_table.cpp", table_source(manifest))) {
        return 1;
    }

    std::cout << "embedded " << manifest.entries.size() << " files in "
        << manifest.chunks.size() << " chunks\n";
    return 0;
}
